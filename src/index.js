import { compileLuaSubset } from "./compiler.js";

const MAX_SOURCE_LENGTH = 200_000;

function json(data, status = 200) {
  return new Response(JSON.stringify(data), {
    status,
    headers: {
      "Content-Type": "application/json; charset=utf-8",
      "Cache-Control": "no-store",
      "X-Content-Type-Options": "nosniff"
    }
  });
}

export default {
  async fetch(request, env) {
    const url = new URL(request.url);

    if (url.pathname === "/api/health") {
      return json({ ok: true, service: "LuaMoon", engine: "LuaMoon custom VM subset" });
    }

    if (url.pathname === "/api/obfuscate") {
      if (request.method !== "POST") {
        return json({ error: "Use POST for this endpoint." }, 405);
      }

      const contentType = request.headers.get("content-type") || "";
      if (!contentType.toLowerCase().includes("application/json")) {
        return json({ error: "Content-Type must be application/json." }, 415);
      }

      const declaredLength = Number(request.headers.get("content-length") || 0);
      if (declaredLength > MAX_SOURCE_LENGTH * 4) {
        return json({ error: "Request too large." }, 413);
      }

      let data;
      try {
        const raw = await request.text();
        if (raw.length > MAX_SOURCE_LENGTH * 4) {
          return json({ error: "Request too large." }, 413);
        }
        data = JSON.parse(raw || "{}");
      } catch {
        return json({ error: "Invalid JSON request." }, 400);
      }

      if (typeof data.source !== "string" || !data.source.trim()) {
        return json({ error: "Enter Lua source code first." }, 400);
      }
      if (data.source.length > MAX_SOURCE_LENGTH) {
        return json({ error: "Source limit is 200,000 characters." }, 413);
      }

      try {
        const output = compileLuaSubset(data.source);
        return json({
          output,
          note: "Generated by the LuaMoon custom VM subset. Test it in your target Lua/Luau runtime."
        });
      } catch (error) {
        return json({ error: error?.message || "Compilation failed." }, 400);
      }
    }

    return env.ASSETS.fetch(request);
  }
};
