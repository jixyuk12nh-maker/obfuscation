import { compileLuaSubset } from "./compiler.js";

const MAX_SOURCE_BYTES = 50 * 1024 * 1024;
const MAX_REQUEST_BYTES = 55 * 1024 * 1024;

function json(data, status = 200) {
  return new Response(JSON.stringify(data), {
    status,
    headers: {
      "Content-Type": "application/json; charset=utf-8",
      "Cache-Control": "no-store",
      "X-Content-Type-Options": "nosniff"
    }
  });
}

export default {
  async fetch(request, env) {
    const url = new URL(request.url);

    if (url.pathname === "/api/health") {
      return json({ ok: true, service: "LuaMoon", engine: "LuaMoon VM security update with closures and control-flow padding" });
    }

    if (url.pathname === "/api/obfuscate") {
      if (request.method !== "POST") {
        return json({ error: "Use POST for this endpoint." }, 405);
      }

      const contentType = request.headers.get("content-type") || "";
      if (!contentType.toLowerCase().includes("application/json")) {
        return json({ error: "Content-Type must be application/json." }, 415);
      }

      const declaredLength = Number(request.headers.get("content-length") || 0);
      if (declaredLength > MAX_REQUEST_BYTES) {
        return json({ error: "Request too large. Maximum request size is 55 MiB." }, 413);
      }

      let data;
      try {
        const raw = await request.text();
        if (new TextEncoder().encode(raw).byteLength > MAX_REQUEST_BYTES) {
          return json({ error: "Request too large. Maximum request size is 55 MiB." }, 413);
        }
        data = JSON.parse(raw || "{}");
      } catch {
        return json({ error: "Invalid JSON request." }, 400);
      }

      if (typeof data.source !== "string" || !data.source.trim()) {
        return json({ error: "Enter Lua source code first." }, 400);
      }

      const sourceBytes = new TextEncoder().encode(data.source).byteLength;
      if (sourceBytes > MAX_SOURCE_BYTES) {
        return json({ error: "Source limit is 50 MiB." }, 413);
      }

      try {
        const output = compileLuaSubset(data.source);
        return json({
          output,
          note: "Generated by LuaMoon VM Security Update. Supported subset includes basic tables/indexing, positional function parameters, single-value returns, and ordinary closures. This is not full Lua 5.1 or Luau; multiple returns, varargs, for-loops, method calls, and full lexical shadowing remain unsupported. Dynamic code loading is required. Test in the exact target runtime."
        });
      } catch (error) {
        return json({ error: error?.message || "Compilation failed." }, 400);
      }
    }

    return env.ASSETS.fetch(request);
  }
};
